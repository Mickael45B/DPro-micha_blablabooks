import Book from "./book.js";
import bookHasLibrary from "./bookHasLibrary.js";
import Library from "./library.js";
import Review from "./review.js";
import User from "./user.js";
import Sequelize from "../db/clientSequelize.js";
//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
//                                                                                              RELATION ENTRE : Book ET Library
//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

Book.belongsToMany(Library, {
	through: bookHasLibrary,
	foreignKey: "id_book",
	otherKey: "id_library",
	as: "putInTheLibrary",
});

Library.belongsToMany(Book, {
	through: bookHasLibrary,
	foreignKey: "id_library",
	otherKey: "id_book",
	as: "isInTheLibrary",
});

//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
//                                                                                              RELATION ENTRE : Library ET user
//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

User.hasMany(Library, { foreignKey: "id_user", as: "libraries" });
Library.belongsTo(User, { foreignKey: "id_user", as: "owner" });

//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
//                                                                                              RELATION ENTRE : user ET Review
//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

User.hasMany(Review, { foreignKey: "id_user", as: "reviews" });
Review.belongsTo(User, { foreignKey: "id_user", as: "reviewer" });

//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
//                                                                                              RELATION ENTRE : Review ET Book
//---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

Book.hasMany(Review, { foreignKey: "id_book", as: "reviewInTheBook" });
Review.belongsTo(Book, { foreignKey: "id_book", as: "reviewedBook" });

export { Book, bookHasLibrary, Library, Review, User, Sequelize };
